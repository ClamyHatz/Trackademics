    /*
     * ========================================================================
     *                          TESTFX UI TEST
     * ========================================================================
     * Critical edge case: grades.fxml is opened while nobody is logged in.
     * This verifies that the FXML loads with GradesController, initialization
     * runs successfully, private controller handlers are wired by FXML, and
     * grade data controls are hidden from an unauthenticated user.
     */

    @Test
    public void loggedOutUserCannotSeeGradeControlsTest() throws Exception {
        Session.clear();

        URL gradesFxml = GradeTest.class.getResource("/grades.fxml");
        assertNotNull(gradesFxml, "grades.fxml must be available in src/main/resources");

        Parent root = new FXMLLoader(gradesFxml).load();
        interact(() -> stage.setScene(new Scene(root, 1180, 760)));

        Label loggedOutLabel = lookup("#loggedOutLabel").queryAs(Label.class);
        Label topGradesLabel = lookup("#topGradesLabel").queryAs(Label.class);
        TableView<?> gradesTable = lookup("#gradesTable").queryAs(TableView.class);
        ComboBox<?> viewByComboBox = lookup("#viewByComboBox").queryAs(ComboBox.class);
        ComboBox<?> classSelectionComboBox = lookup("#classSelectionComboBox").queryAs(ComboBox.class);
        ComboBox<?> selectionComboBox = lookup("#selectionComboBox").queryAs(ComboBox.class);

        assertTrue(loggedOutLabel.isVisible());
        assertTrue(loggedOutLabel.isManaged());
        assertEquals("User Logged Out", loggedOutLabel.getText());
        assertEquals("No Grades Shown", topGradesLabel.getText());

        assertFalse(gradesTable.isVisible());
        assertFalse(gradesTable.isManaged());
        assertFalse(viewByComboBox.isVisible());
        assertFalse(classSelectionComboBox.isVisible());
        assertFalse(selectionComboBox.isVisible());
    }
