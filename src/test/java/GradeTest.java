    @BeforeEach
    public void setUpDatabase() throws Exception {
        connection = DriverManager.getConnection("jdbc:h2:mem:gradeTest");

        try (Statement statement = connection.createStatement()) {
            statement.execute("DROP TABLE IF EXISTS grades");
            statement.execute(
                    "CREATE TABLE grades ("
                            + "grade_id INTEGER "
                            + "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                            + "enrollment_id INTEGER NOT NULL, "
                            + "assignment_id INTEGER NOT NULL, "
                            + "grade DOUBLE NOT NULL, "
                            + "weight DOUBLE NOT NULL"
                            + ")");
        }

        gradeDao = new GradeDao(connection);
    }

    @AfterEach
    public void tearDownDatabase() throws Exception {
        Session.clear();

        if (connection != null && !connection.isClosed()) {
            connection.close();
        }
    }

    /*
     * ========================================================================
     *                         GRADE MODEL TESTS
     * ========================================================================
     * These tests verify the Grade data object itself, including construction,
     * mutation, equality, hashCode, and toString behavior.
     */

    @Test
    public void gradeConstructorAndGettersTest() {
        Grade grade = new Grade(7, 11, 22, 95.5, 0.25);

        assertEquals(7, grade.getGradeId());
        assertEquals(11, grade.getEnrollmentId());
        assertEquals(22, grade.getAssignmentId());
        assertEquals(95.5, grade.getGrade(), 0.001);
        assertEquals(0.25, grade.getWeight(), 0.001);
    }

    @Test
    public void newGradeStartsWithZeroIdTest() {
        Grade grade = new Grade(11, 22, 88.0, 0.40);

        assertEquals(0, grade.getGradeId());
    }

    @Test
    public void gradeSettersChangeEveryFieldTest() {
        Grade grade = new Grade(1, 2, 70.0, 0.10);

        grade.setGradeId(9);
        grade.setEnrollmentId(10);
        grade.setAssignmentId(20);
        grade.setGrade(99.0);
        grade.setWeight(0.75);

        assertEquals(9, grade.getGradeId());
        assertEquals(10, grade.getEnrollmentId());
        assertEquals(20, grade.getAssignmentId());
        assertEquals(99.0, grade.getGrade(), 0.001);
        assertEquals(0.75, grade.getWeight(), 0.001);
    }

    @Test
    public void equalGradesHaveEqualHashCodesTest() {
        Grade first = new Grade(3, 4, 5, 91.0, 0.30);
        Grade second = new Grade(3, 4, 5, 91.0, 0.30);

        assertEquals(first, second);
        assertEquals(first.hashCode(), second.hashCode());
    }

    @Test
    public void changingOneGradeFieldBreaksEqualityTest() {
        Grade first = new Grade(3, 4, 5, 91.0, 0.30);
        Grade second = new Grade(3, 4, 5, 91.0, 0.30);

        second.setGrade(90.0);

        assertNotEquals(first, second);
        assertNotEquals(first, null);
        assertNotEquals(first, "not a grade");
    }

    @Test
    public void gradeToStringContainsImportantValuesTest() {
        Grade grade = new Grade(3, 4, 5, 91.0, 0.30);
        String text = grade.toString();

        assertTrue(text.contains("gradeId=3"));
        assertTrue(text.contains("enrollmentId=4"));
        assertTrue(text.contains("assignmentId=5"));
        assertTrue(text.contains("grade=91.0"));
        assertTrue(text.contains("weight=0.3"));
    }

    /*
     * ========================================================================
     *                         GRADE DAO TESTS
     * ========================================================================
     * These are database integration tests using H2. They test the complete
     * CRUD path plus filtering methods and failure cases instead of only the
     * successful insert/find path.
     */

    @Test
    public void insertAndFindByIdTest() throws Exception {
        Grade grade = new Grade(1, 2, 95.5, 0.25);

        gradeDao.insert(grade);

        assertTrue(grade.getGradeId() > 0);

        Grade savedGrade = gradeDao.findById(grade.getGradeId());

        assertNotNull(savedGrade);
        assertEquals(grade, savedGrade);
    }

    @Test
    public void findByIdReturnsNullForMissingGradeTest() throws Exception {
        assertNull(gradeDao.findById(999999));
    }

    @Test
    public void findAllReturnsEveryGradeInIdOrderTest() throws Exception {
        Grade first = new Grade(1, 10, 75.0, 0.20);
        Grade second = new Grade(2, 20, 85.0, 0.30);
        Grade third = new Grade(3, 30, 95.0, 0.50);

        gradeDao.insert(first);
        gradeDao.insert(second);
        gradeDao.insert(third);

        List<Grade> grades = gradeDao.findAll();

        assertEquals(3, grades.size());
        assertEquals(first, grades.get(0));
        assertEquals(second, grades.get(1));
        assertEquals(third, grades.get(2));
    }

    @Test
    public void findByEnrollmentIdDoesNotLeakOtherStudentsGradesTest() throws Exception {
        Grade wantedOne = new Grade(100, 1, 88.0, 0.25);
        Grade otherEnrollment = new Grade(200, 1, 99.0, 0.25);
        Grade wantedTwo = new Grade(100, 2, 77.0, 0.25);

        gradeDao.insert(wantedOne);
        gradeDao.insert(otherEnrollment);
        gradeDao.insert(wantedTwo);

        List<Grade> grades = gradeDao.findByEnrollmentId(100);

        assertEquals(2, grades.size());
        assertTrue(grades.stream().allMatch(g -> g.getEnrollmentId() == 100));
        assertTrue(grades.contains(wantedOne));
        assertTrue(grades.contains(wantedTwo));
        assertFalse(grades.contains(otherEnrollment));
    }

    @Test
    public void findByAssignmentIdDoesNotIncludeOtherAssignmentsTest() throws Exception {
        Grade wantedOne = new Grade(1, 50, 88.0, 0.25);
        Grade otherAssignment = new Grade(1, 60, 99.0, 0.25);
        Grade wantedTwo = new Grade(2, 50, 77.0, 0.25);

        gradeDao.insert(wantedOne);
        gradeDao.insert(otherAssignment);
        gradeDao.insert(wantedTwo);

        List<Grade> grades = gradeDao.findByAssignmentId(50);

        assertEquals(2, grades.size());
        assertTrue(grades.stream().allMatch(g -> g.getAssignmentId() == 50));
        assertTrue(grades.contains(wantedOne));
        assertTrue(grades.contains(wantedTwo));
        assertFalse(grades.contains(otherAssignment));
    }

    @Test
    public void updatePersistsEveryChangedFieldTest() throws Exception {
        Grade grade = new Grade(1, 2, 70.0, 0.10);
        gradeDao.insert(grade);

        grade.setEnrollmentId(10);
        grade.setAssignmentId(20);
        grade.setGrade(98.5);
        grade.setWeight(0.80);

        gradeDao.update(grade);

        Grade updated = gradeDao.findById(grade.getGradeId());

        assertNotNull(updated);
        assertEquals(10, updated.getEnrollmentId());
        assertEquals(20, updated.getAssignmentId());
        assertEquals(98.5, updated.getGrade(), 0.001);
        assertEquals(0.80, updated.getWeight(), 0.001);
    }

    @Test
    public void deleteActuallyRemovesGradeTest() throws Exception {
        Grade grade = new Grade(1, 2, 70.0, 0.10);
        gradeDao.insert(grade);

        gradeDao.delete(grade.getGradeId());

        assertNull(gradeDao.findById(grade.getGradeId()));
        assertTrue(gradeDao.findAll().isEmpty());
    }

    /*
     * ========================================================================
     *                    DAO EDGE / FAILURE CASE TESTS
     * ========================================================================
     * These deliberately use IDs that do not exist. Silent success here could
     * hide application bugs, so GradeDao is expected to report the problem.
     */

    @Test
    public void updatingMissingGradeThrowsSQLExceptionTest() {
        Grade missing = new Grade(999999, 1, 2, 80.0, 0.25);

        SQLException exception = assertThrows(
                SQLException.class,
                () -> gradeDao.update(missing));

        assertTrue(exception.getMessage().contains("999999"));
    }

    @Test
    public void deletingMissingGradeThrowsSQLExceptionTest() {
        SQLException exception = assertThrows(
                SQLException.class,
                () -> gradeDao.delete(999999));

        assertTrue(exception.getMessage().contains("999999"));
    }

